class TestDegradation:
    async def test_selector_probe_failure_degrades_to_host_honestly(
        self,
        monkeypatch: pytest.MonkeyPatch,
        patch_platform: Callable[[str], None],
        patch_shell: Callable[[str | None], None],
    ) -> None:
        """The selector (selection.resolve_selection) probes seatbelt; a
        failed probe yields HostRuntime(reason) — the reason lands in
        ResolvedSandbox verbatim (honest reporting)."""
        import modex_agent.sandbox.selection as selection_mod
        from modex_agent.sandbox.selection import resolve_selection, select_runtime

        monkeypatch.setattr(
            selection_mod, "_get_platform", lambda: Platform.MACOS
        )
        patch_shell("/bin/bash")

        async def failing_probe() -> ProbeResult:
            return ProbeResult(available=False, detail="not found on PATH")

        monkeypatch.setattr(selection_mod, "probe_seatbelt", failing_probe)

        selection = await resolve_selection(SandboxBackend.AUTO)
        resolved = await select_runtime(selection).resolve(
            SandboxSettings(policy=SandboxPolicy.WORKSPACE_WRITE), WS
        )
        assert resolved.backend is SandboxBackend.HOST
        assert resolved.enforcement is EnforcementLevel.NONE
        assert resolved.degraded_reason is not None
        assert "sandbox-exec" in resolved.degraded_reason

    async def test_non_macos_is_host(
        self,
        monkeypatch: pytest.MonkeyPatch,
        patch_platform: Callable[[str], None],
        patch_shell: Callable[[str | None], None],
    ) -> None:
        patch_platform("linux")
        patch_shell("/bin/bash")

        resolved = await SeatbeltRuntime().resolve(
            SandboxSettings(policy=SandboxPolicy.WORKSPACE_WRITE), WS
        )
        assert resolved.backend is SandboxBackend.HOST
        assert resolved.degraded_reason is not None
        assert "macOS" in resolved.degraded_reason
