class TestProfileReadOnly:
    def test_snapshot_with_network_denied(self) -> None:
        settings = SandboxSettings(policy=SandboxPolicy.READ_ONLY, network=False)
        assert compile_seatbelt_profile(settings, WS) == (
            "(version 1)\n"
            "\n"
            ";; generated by modex_agent.sandbox.seatbelt_runtime - do not edit\n"
            "\n"
            ";; read-only: everything readable, nothing writable\n"
            "(allow file-read*)\n"
            "(deny file-write*)\n"
            "(deny network*)\n"
        )

    def test_snapshot_with_network_allowed(self) -> None:
        settings = SandboxSettings(policy=SandboxPolicy.READ_ONLY, network=True)
        profile = compile_seatbelt_profile(settings, WS)
        assert "(deny network*)" not in profile
        assert "(deny file-write*)" in profile


class TestProfileWorkspaceWrite:
    def test_snapshot_default_protected_git(self) -> None:
        settings = SandboxSettings(policy=SandboxPolicy.WORKSPACE_WRITE, network=False)
        assert compile_seatbelt_profile(settings, WS) == (
            "(version 1)\n"
            "\n"
            ";; generated by modex_agent.sandbox.seatbelt_runtime - do not edit\n"
            "\n"
            ";; workspace-write: everything readable, writes denied by default\n"
            "(allow file-read*)\n"
            "(deny file-write*)\n"
            f'(allow file-write* (subpath "{WS.as_posix()}"))\n'
            f'(deny file-write* (subpath "{WS.as_posix()}/.git"))\n'
            "(deny network*)\n"
        )

    def test_snapshot_extra_writable_roots_and_protected_subpaths(self) -> None:
        build_root = Path("/tmp/build").resolve()
        log_root = Path("/var/log/app").resolve()
        settings = SandboxSettings(
            policy=SandboxPolicy.WORKSPACE_WRITE,
            network=True,
            writable_roots=[build_root, log_root],
            protected_subpaths=[".git", "secrets"],
        )
        profile = compile_seatbelt_profile(settings, WS)
        # Allow rules for every writable root (workspace first, then declared).
        assert (
            f'(allow file-write* (subpath "{WS.as_posix()}"))\n'
            f'(allow file-write* (subpath "{build_root.as_posix()}"))\n'
            f'(allow file-write* (subpath "{log_root.as_posix()}"))\n'
        ) in profile
        # Deny rules for every protected subpath of every root, AFTER the
        # allows (SBPL: the last matching rule wins — the trailing deny
        # shadows the broader allow).
        deny_block = (
            f'(deny file-write* (subpath "{WS.as_posix()}/.git"))\n'
            f'(deny file-write* (subpath "{WS.as_posix()}/secrets"))\n'
            f'(deny file-write* (subpath "{build_root.as_posix()}/.git"))\n'
            f'(deny file-write* (subpath "{build_root.as_posix()}/secrets"))\n'
            f'(deny file-write* (subpath "{log_root.as_posix()}/.git"))\n'
            f'(deny file-write* (subpath "{log_root.as_posix()}/secrets"))\n'
        )
        assert deny_block in profile
        assert profile.index(deny_block) > profile.index(
            f'(allow file-write* (subpath "{log_root.as_posix()}"))'
        )
        # network=True → no network deny.
        assert "(deny network*)" not in profile

    def test_empty_protected_subpaths_only_allows(self) -> None:
        settings = SandboxSettings(
            policy=SandboxPolicy.WORKSPACE_WRITE,
            network=False,
            protected_subpaths=[],
        )
        profile = compile_seatbelt_profile(settings, WS)
        assert profile.count("(deny file-write*") == 1  # only the global deny


