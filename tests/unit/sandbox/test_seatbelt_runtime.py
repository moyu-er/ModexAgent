class TestResolveArgv:
    async def test_shell_argv_shape_and_profile_file_exists(
        self,
        monkeypatch: pytest.MonkeyPatch,
        patch_platform: Callable[[str], None],
        patch_shell: Callable[[str | None], None],
    ) -> None:
        patch_platform("darwin")
        patch_shell("/bin/bash")

        settings = SandboxSettings(policy=SandboxPolicy.WORKSPACE_WRITE)
        resolved = await SeatbeltRuntime().resolve(settings, WS)

        assert resolved.backend is SandboxBackend.LOCAL
        assert resolved.enforcement is EnforcementLevel.FULL
        assert resolved.degraded_reason is None

        # shell_argv = sandbox-exec -f <profile> + host bash tail.
        assert resolved.shell_argv[0] == "sandbox-exec"
        assert resolved.shell_argv[1] == "-f"
        profile_path = Path(resolved.shell_argv[2])
        assert profile_path.exists()
        assert profile_path.suffix == ".sb"
        assert resolved.shell_argv[3:] == ["/bin/bash", "--noprofile", "--norc", "-i"]

        # The temp file carries exactly the compiled profile.
        expected_profile = compile_seatbelt_profile(settings, WS)
        assert profile_path.read_text(encoding="utf-8") == expected_profile

        # One-shot prefix is the same wrapper without the shell tail.
        assert resolved.one_shot_command_argv_prefix == [
            "sandbox-exec",
            "-f",
            str(profile_path),
        ]

    async def test_no_bash_found_empty_shell_argv(
        self,
        monkeypatch: pytest.MonkeyPatch,
        patch_platform: Callable[[str], None],
        patch_shell: Callable[[str | None], None],
    ) -> None:
        patch_platform("darwin")
        patch_shell(None)

        resolved = await SeatbeltRuntime().resolve(
            SandboxSettings(policy=SandboxPolicy.WORKSPACE_WRITE), WS
        )
        assert resolved.shell_argv == []
        # One-shot prefix still carries the wrapper.
        assert resolved.one_shot_command_argv_prefix[0] == "sandbox-exec"


