class TestProfileBoundaryTruth:
    """The profile must be a real boundary — the anti-regression class."""

    @pytest.mark.parametrize(
        ("policy", "network"),
        [
            (SandboxPolicy.READ_ONLY, False),
            (SandboxPolicy.READ_ONLY, True),
            (SandboxPolicy.WORKSPACE_WRITE, False),
            (SandboxPolicy.WORKSPACE_WRITE, True),
        ],
    )
    def test_bounded_policies_never_allow_default(
        self, policy: SandboxPolicy, network: bool
    ) -> None:
        """The legacy isolation.py bug was (allow default) — fake isolation."""
        settings = SandboxSettings(policy=policy, network=network)
        profile = compile_seatbelt_profile(settings, WS)
        assert "(allow default)" not in profile
        assert "(deny file-write*)" in profile
        assert profile.startswith("(version 1)")


