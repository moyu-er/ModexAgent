"""Tests for SeatbeltRuntime — profile compilation and argv resolution.

Ticket 06 (docs/design/sandbox-integration/tickets.md):

- profile text snapshot matrix: READ_ONLY / WORKSPACE_WRITE /
  DANGER_FULL_ACCESS × network on/off × writable_roots / protected_subpaths
- the generated profile is a *real* boundary: global ``deny file-write*`` is
  always present (never the legacy ``(allow default)`` fake isolation);
  protected-subpath denies come after the allows (SBPL: last rule wins)
- argv shape: ``sandbox-exec -f <profile>`` + host bash tail; the profile
  temp file exists on disk and its bytes equal the compiled profile
- degradation: probe failure → HOST with a degraded_reason (honest
  reporting); non-macOS construction → HOST as well
"""

